"""The Slice mark: a strip of film cut into three, the middle piece lifted out in the accent.

One geometry for both the launcher icon (writes app/src/main/res/drawable/ic_launcher_fg.xml,
108×108 adaptive-icon viewport, safe zone 21..87) and the README logo (make_art.py).
Run: python docs/tools/icon.py
"""
import os

ACCENT = "#FF4D6D"
LIGHT = "#EDEBE6"
BAND_LIGHT = "#D6D2CA"
BAND_ACCENT = "#E8395B"

TOP, BOTTOM, SLANT, GAP, LIFT = 44.0, 64.0, 4.0, 4.0, 5.0
LEFT, RIGHT = 24.0, 84.0
HOLE, PITCH, EDGE = 2.4, 4.4, 1.6  # sprocket hole size, spacing, inset from the strip edge


def pieces():
    """[(polygon, holes, band, is_accent)] in viewport units."""
    cut1, cut2 = 43.0, 65.0  # where the cuts cross the strip's middle
    out = []
    spans = [(None, cut1), (cut1, cut2), (cut2, None)]
    for i, (a, b) in enumerate(spans):
        dy = -LIFT if i == 1 else 0.0
        top, bot = TOP + dy, BOTTOM + dy

        def left(y):
            if a is None:
                return LEFT
            mid = (top + bot) / 2
            return a + GAP / 2 + (mid - y) / (bot - top) * SLANT * 2 * 0.5

        def right(y):
            if b is None:
                return RIGHT
            mid = (top + bot) / 2
            return b - GAP / 2 + (mid - y) / (bot - top) * SLANT * 2 * 0.5

        poly = [(left(top), top), (right(top), top), (right(bot), bot), (left(bot), bot)]
        holes = []
        for row in (top + EDGE, bot - EDGE - HOLE):
            x0 = max(left(row), left(row + HOLE)) + EDGE
            x1 = min(right(row), right(row + HOLE)) - EDGE
            n = int((x1 - x0 + PITCH - HOLE) // PITCH)
            start = x0 + ((x1 - x0) - (n * PITCH - (PITCH - HOLE))) / 2
            for k in range(n):
                hx = start + k * PITCH
                holes.append((hx, row, hx + HOLE, row + HOLE))
        bt, bb = top + EDGE * 2 + HOLE, bot - EDGE * 2 - HOLE
        band = [(left(bt), bt), (right(bt), bt), (right(bb), bb), (left(bb), bb)]
        out.append((poly, holes, band, i == 1))
    return out


def _path(poly, holes=()):
    f = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")
    d = "M" + "L".join(f"{f(x)},{f(y)}" for x, y in poly) + "Z"
    for x0, y0, x1, y1 in holes:
        d += f"M{f(x0)},{f(y0)}h{f(x1 - x0)}v{f(y1 - y0)}h{f(x0 - x1)}z"
    return d


def vector_xml():
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by docs/tools/icon.py: a strip of film cut into three, the middle piece",
        "     lifted out in the accent. Sprocket holes are cut out (evenOdd) so themed icons work.",
        "     Safe zone is the centre 66dp (21..87). -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp" android:height="108dp"',
        '    android:viewportWidth="108" android:viewportHeight="108">',
    ]
    for poly, holes, band, accent in pieces():
        lines.append(f'    <path android:fillColor="{ACCENT if accent else LIGHT}" android:fillType="evenOdd"')
        lines.append(f'        android:pathData="{_path(poly, holes)}" />')
        lines.append(f'    <path android:fillColor="{BAND_ACCENT if accent else BAND_LIGHT}"')
        lines.append(f'        android:pathData="{_path(band)}" />')
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    out = os.path.join(root, "app", "src", "main", "res", "drawable", "ic_launcher_fg.xml")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(vector_xml())
    print("wrote", out)
